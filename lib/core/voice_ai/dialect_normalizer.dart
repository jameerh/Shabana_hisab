  static double? normalizeNumber(String word) {
    String w = word.trim();
    
    // Handle Devanagari digits (०-९)
    String digitNorm = w.replaceAll('०', '0').replaceAll('१', '1').replaceAll('२', '2')
                        .replaceAll('३', '3').replaceAll('४', '4').replaceAll('५', '5')
                        .replaceAll('६', '6').replaceAll('७', '7').replaceAll('८', '8')
                        .replaceAll('९', '9');
    
    double? directVal = double.tryParse(digitNorm);
    if (directVal != null) return directVal;

    if (_localNumbers.containsKey(w)) return _localNumbers[w];
    
    // Handle "साडे" prefix (e.g., "साडेपाचशे" -> 550)
    if (w.startsWith('साडे')) {
      final base = w.substring(4);
      if (_localNumbers.containsKey(base)) {
        double val = _localNumbers[base]!;
        return val + (val >= 100 ? 50 : 0.5);
      }
    }
    
    // Handle "पावणे" prefix (e.g., "पावणेतीनशे" -> 275)
    if (w.startsWith('पावणे')) {
      final base = w.substring(5);
      if (_localNumbers.containsKey(base)) {
        double val = _localNumbers[base]!;
        return val - (val >= 100 ? 25 : 0.25);
      }
    }

    return null;
  }

  static String? normalizeOperator(String word) {
    return _operators[word.toLowerCase()];
  }

  static String cleanNoise(String text) {
    final noise = ['अरे', 'अं', 'हो', 'जरा', 'पण', 'ते', 'अहो', 'please', 'total', 'कर', 'करा', 'रुपये', 'रुपया'];
    String result = text;
    for (var word in noise) {
      result = result.replaceAll(RegExp('\\b$word\\b'), '');
    }
    return result.trim().replaceAll(RegExp(' +'), ' ');
  }
